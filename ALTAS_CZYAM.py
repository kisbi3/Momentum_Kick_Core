# Fourier Series 함수 정의
def fourier_series(x, *a):
    res = a[0]
    for deg in range(1, len(a)):
        res += a[deg]*np.cos(deg*x) + a[deg]*np.sin(deg*x)
    return res

# curve_fit 함수를 이용해 데이터를 fitting
popt, pcov = curve_fit(fourier_series, x, y, p0=[1.0]*6)

# 원본 데이터와 fitting 결과를 그래프로 표현
plt.scatter(x, y, label='original data')
plt.plot(x, fourier_series(x, *popt), 'r-', label='fit: a=%5.3f, b=%5.3f' % tuple(popt))
plt.xlabel('x')
plt.ylabel('y')
plt.legend()
plt.show()
